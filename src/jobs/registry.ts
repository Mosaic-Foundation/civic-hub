export function jobById(id: string): JobSpec | undefined {
  return JOBS.find((j) => j.id === id);
}

/** The full Express path of a job route, e.g. `/internal/digest/run`. */
export function internalPath(job: JobSpec, path: string = job.path): string {
  return `${JOBS_MOUNT}${path}`;
}

/** vercel.json's "crons" section, in registry order. */
export function vercelCrons(): Array<{ path: string; schedule: string }> {
  return JOBS.map((job) => ({
    path: `${VERCEL_API_PREFIX}${internalPath(job)}`,
    schedule: job.schedule,
  }));
}

/**
 * A crontab for a deployment that is not on Vercel. Each line GETs the job's
 * route with the CRON_SECRET bearer, exactly as Vercel Cron does. `baseUrl`
 * and the secret are left as shell variables unless given, so the output can
 * be installed as-is on a host that exports them.
 */
export function crontab(
  opts: { baseUrl?: string; prefix?: string } = {},
): string {
  const base = opts.baseUrl ?? "${CIVIC_CRON_BASE_URL}";
  const prefix = opts.prefix ?? VERCEL_API_PREFIX;
  const lines = [
    "# civic-hub scheduled jobs — generated by `npm run jobs:crontab` from src/jobs/registry.ts.",
    "# Times are UTC. Each run covers every active hub; a hub with the plugin off is skipped.",
    "CRON_TZ=UTC",
  ];
  for (const job of JOBS) {
    lines.push(`# ${job.id}: ${job.description}`);
    lines.push(
      `${job.schedule} curl -fsS -H "Authorization: Bearer $CRON_SECRET" "${base}${prefix}${internalPath(job)}"`,
    );
  }
  return `${lines.join("\n")}\n`;
}
