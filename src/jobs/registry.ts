// Every scheduled job, in one list.
//
// Before Phase 2c the same fact lived in three places that nothing kept in
// step: vercel.json's "crons", the /internal mounts in app.ts, and the route
// docs. A job added to one and forgotten in another either never ran or ran
// with no route behind it. This list is the one place; the others are derived
// from it or checked against it:
//
//   - the /internal/*/run routes are mounted from it (src/routes/jobRoutes.ts);
//   - vercel.json's "crons" must equal vercelCrons() (tests/unit/jobRegistry
//     .test.ts fails on any difference; `npm run jobs:crontab -- --vercel`
//     prints the section to paste);
//   - `npm run jobs:crontab` prints a crontab for a deployment that is not on
//     Vercel, so a self-hosted hub schedules exactly the same jobs.
//
// Pure data by construction — no imports from the app — so the crontab script
// and the test can read it without booting anything. What each job DOES is in
// src/jobs/runners.ts, keyed on the same ids.
//
// Every schedule is UTC (Vercel Cron's only time zone, and cron's default).
// A job that must honour a hub's local time runs more often and decides per
// hub whether it is due: the resident digest runs hourly and sends to a hub
// only in the hour that hub chose, in the hub's own time zone.

import type { PluginId } from "../models/hubSettings.js";

export interface JobSpec {
  /** Stable id, also the key into the runner table. */
  readonly id: string;
  /** The plugin this job belongs to. `plugin.<id>.enabled` off skips it per hub. */
  readonly plugin: PluginId;
  /** Path under /internal. Vercel calls it with a GET and the CRON_SECRET bearer. */
  readonly path: string;
  /** Five-field cron expression, UTC. */
  readonly schedule: string;
  /** One line for the route docs and the crontab comment. */
  readonly description: string;
  /**
   * Older paths still mounted to the same job but never scheduled. Each one
   * is on its way out and says why beside it.
   */
  readonly deprecatedPaths?: readonly string[];
}

/** Where the job routes are mounted in the Express app. */
export const JOBS_MOUNT = "/internal";

/**
 * What Vercel puts in front of every Express path: `/api/:path*` is rewritten
 * to the one function, and the prefix is stripped before Express sees it.
 */
export const VERCEL_API_PREFIX = "/api";

