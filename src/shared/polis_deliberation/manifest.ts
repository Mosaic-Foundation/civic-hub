// conversation: the process type's manifest (src/processes/manifest.ts; ADR-009).
// Plain data: the registry, the wire, the settings page, the feed and the UI
// are built from it. The host wiring (src/processes/deliberationBoot.ts)
// pairs it with the portable handler (./handler.ts).

import { defineManifest } from "../../processes/manifest.js";
import type { ProcessTypeDescriptor } from "../../processes/descriptor.js";
import { DEADLINE_CLOSE_INPUT } from "../deadlineClose.js";

/**
 * What a Polis conversation is (src/processes/descriptor.ts). Residents take
 * part in Polis itself, so every action here is an admin's or the hub's:
 * approval runs start (best effort), the deadline runs close, and the
 * conversation's summary is regenerated by an admin. Nothing in the hub
 * dispatches poll_state; an admin could, and it closes the conversation when
 * the participant goal or the deadline has been reached.
 *
 * Creation: residents draft and submit one; every submission goes through
 * review, which approves it into draft and then runs start. createProcess
 * alone, with no status on the state, leaves it active, which is what
 * `initial_status` says.
 *
 * Tier 3: Polis is an outside service reached through one adapter.
 *
 * Lifecycle: draft, active, closed. Its brief, when published, finalizes the
 * conversation (finalizeBriefSource), so a published one is finalized.
 */
const descriptor: ProcessTypeDescriptor = {
  type: "civic.polis_deliberation",
  version: "0.1",
  tier: 3,
  plugin: "conversation",
  states: ["draft", "active", "closed", "finalized"],
  initial_status: "active",
  actions: [
    {
      name: "start",
      description: "Open the conversation in Polis and for participants",
      callers: ["admin", "system"],
      from: ["draft"],
      to: "active",
      emits: ["civic.process.started"],
    },
    {
      name: "close",
      description: "Close the conversation and summarize what was said",
      callers: ["admin", "system"],
      from: ["active"],
      to: "closed",
      emits: ["civic.process.ended"],
      input_schema: DEADLINE_CLOSE_INPUT,
    },
    {
      name: "poll_state",
      description: "Read the conversation's progress; closes it at the participant goal or the deadline",
      callers: ["admin"],
      from: ["active"],
      to: ["active", "closed"],
      emits: ["civic.process.ended"],
    },
    {
      name: "regenerate_summary",
      description: "Summarize a closed conversation again",
      callers: ["admin"],
      from: ["closed"],
      to: null,
      emits: [],
    },
  ],
  emits: ["civic.process.started", "civic.process.ended"],
  creation: { resident: { drafts: "/deliberations/drafts" }, admin: true, system: false },
  deadline: { action: "close", source: "state.deadline" },
  brief: true,
  tables: ["deliberation_submissions", "deliberation_votes", "deliberation_drafts"],
  outside_services: [
    {
      name: "Polis",
      adapter: "src/shared/polis_deliberation/adapter/polisAdapter.ts",
      egress_setting: "plugin.conversation.polis_url",
      participant_identifier: "account_id",
      service_credential: "shared_service_token",
      service_allowlist: false,
      data_retained: ["statements", "statement votes", "participant identifiers (the hub account id)"],
      export_path: "None from the hub; Polis's own conversation export",
      participation: [
        { method: "POST", path: "/deliberations/:id/participate/statement", body: { text: "A statement from a participant." } },
        { method: "POST", path: "/deliberations/:id/participate/vote", body: { statement_id: 0, vote: "agree" } },
      ],
    },
  ],
  examples: {
    draft: { title: "Conformance conversation", description: "What should the hub know?" },
    create: {
      path: "/deliberations",
      body: { title: "Conformance conversation", topic: "Conformance conversation", framing: "What should the hub know?" },
    },
  },
  // "Discuss" on the phone's bar, where five labels must fit (Adam, 2026-10-14;
  // "Talk" until the navigation polish). Everywhere else says Conversations.
  display: {
    label: "Conversation",
    plural: "Conversations",
    icon: "conversation",
    section: {
      id: "conversations",
      label: "Conversations",
      short: "Discuss",
      path: "/deliberations",
      detail_paths: ["/deliberation/"],
      order: 10,
    },
  },
};

export const POLIS_DELIBERATION_MANIFEST = defineManifest({
  descriptor,
  color: "conversation",
  detailPath: (id) => `/deliberation/${id}`,
  requiredSchema: [
    {
      table: "deliberation_submissions",
      columns: ["process_id", "user_id"],
      owner: "civic.polis_deliberation",
    },
    {
      table: "deliberation_votes",
      columns: ["process_id", "user_id", "statement_id"],
      owner: "civic.polis_deliberation",
    },
  ],
  tables: [
    { name: "deliberation_submissions", rows: "export", key: ["process_id", "user_id"] },
    { name: "deliberation_votes", rows: "export", key: ["process_id", "user_id", "statement_id"] },
    { name: "deliberation_drafts", rows: "export", key: ["id"] },
  ],
  jobs: [],
  pluginSection: { order: 40, fields: [{ key: "plugin.conversation.polis_url", kind: "url" }] },
  activities: {},
  publicListing: "always",
});
