// Print the schedule for every job in src/jobs/registry.ts.
//
//   npm run jobs:crontab                       a crontab for a non-Vercel host
//   npm run jobs:crontab -- --base https://x   ... with the base URL filled in
//   npm run jobs:crontab -- --prefix /internal ... for a plain Express server
//                                              (no /api rewrite in front)
//   npm run jobs:crontab -- --vercel           vercel.json's "crons" section
//   npm run jobs:crontab -- --script [--dir /srv/civic-hub] [--env /etc/civic-hub.env]
//                                              each job run in-process by
//                                              scripts/run-job.ts (no HTTP, no
//                                              CRON_SECRET; RUN-ANYWHERE.md)
//
// vercel.json is checked against the same list by tests/unit/jobRegistry
// .test.ts, so paste the --vercel output there whenever a job changes.
// Reads no environment and touches no database.

import { JOBS, crontab, vercelCrons } from "../src/jobs/registry.js";

const args = process.argv.slice(2);
function flag(name: string): string | undefined {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
}

/** A crontab whose lines run each job with scripts/run-job.ts (ADR-012). */
function scriptCrontab(dir: string, envFile: string): string {
  const lines = [
    "# civic-hub scheduled jobs — generated by `npm run jobs:crontab -- --script` from src/jobs/registry.ts.",
    "# Times are UTC. Each line runs the job for every active hub (a platform job once), in-process.",
    "CRON_TZ=UTC",
  ];
  for (const job of JOBS) {
    lines.push(`# ${job.id}: ${job.description}`);
    lines.push(`${job.schedule} cd ${dir} && node --env-file=${envFile} --import tsx scripts/run-job.ts ${job.id} --all`);
  }
  return `${lines.join("\n")}\n`;
}

if (args.includes("--script")) {
  process.stdout.write(scriptCrontab(flag("--dir") ?? "${CIVIC_HUB_DIR}", flag("--env") ?? "${CIVIC_HUB_ENV_FILE}"));
} else if (args.includes("--vercel")) {
  process.stdout.write(`${JSON.stringify({ crons: vercelCrons() }, null, 2)}\n`);
} else {
  const prefix = flag("--prefix");
  process.stdout.write(
    crontab({ baseUrl: flag("--base"), prefix: prefix === "" ? "" : prefix }),
  );
}
