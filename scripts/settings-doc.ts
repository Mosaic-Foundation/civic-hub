// The settings reference in RUNBOOK-operations.md, generated from
// src/config/settings.ts (ADR-012). Nobody edits that table by hand.
//
//   npm run settings:doc            rewrite the table in RUNBOOK-operations.md
//   npx tsx scripts/settings-doc.ts --check   exit 1 if the table is stale
//
// tests/unit/settings.test.ts runs the check, so a setting added without
// regenerating fails the unit suite.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { SETTINGS, type SettingDecl } from "../src/config/settings.js";
import { ENV_FALLBACKS } from "../src/models/hubSettings.js";

export const RUNBOOK = fileURLToPath(new URL("../RUNBOOK-operations.md", import.meta.url));
const BEGIN = "<!-- settings:begin (generated by scripts/settings-doc.ts; do not edit) -->";
const END = "<!-- settings:end -->";

function required(decl: SettingDecl): string {
  const r = decl.required;
  if (!r) return "no";
  if (r === "always") return "**always**";
  if (r === "production") return "**in production**";
  return `when ${r.when} is ${r.when === "CIVIC_HUB_MINTED_TOKEN" ? "on" : "set"}`;
}

const cell = (v: string) => v.replaceAll("|", "\\|");

export function settingsTable(): string {
  const rows = (Object.entries(SETTINGS) as Array<[string, SettingDecl]>).map(([name, d]) => {
    const names = [
      `\`${name}\``,
      ...(d.hostNames ?? []).map((n) => `\`${n}\` (host, read first)`),
      ...(d.aliases ?? []).map((n) => `\`${n}\` (older name)`),
    ].join("<br>");
    return `| ${names} | ${d.layer} | ${d.type} | ${required(d)} | ${d.default ? `\`${d.default}\`` : ""} | ${cell(d.purpose)} |`;
  });
  const fallbacks = [...new Set(Object.values(ENV_FALLBACKS).flat())].sort().map((n) => `\`${n}\``).join(", ");
  return [
    BEGIN,
    "",
    "| Setting | Layer | Type | Required | Default | Purpose |",
    "|---|---|---|---|---|---|",
    ...rows,
    "",
    "**Hub-setting fallbacks.** Read only when a hub has no row of its own for the setting, for a single-hub self-host",
    "with no settings rows (`ENV_FALLBACKS` in `src/models/hubSettings.ts`), never required:",
    fallbacks + ".",
    "",
    END,
  ].join("\n");
}

export function withTable(doc: string): string {
  const a = doc.indexOf(BEGIN);
  const b = doc.indexOf(END);
  if (a < 0 || b < 0) throw new Error(`RUNBOOK-operations.md has no settings markers (${BEGIN})`);
  return doc.slice(0, a) + settingsTable() + doc.slice(b + END.length);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const doc = readFileSync(RUNBOOK, "utf8");
  const next = withTable(doc);
  if (process.argv.includes("--check")) {
    if (next !== doc) {
      console.error("RUNBOOK-operations.md's settings table is stale: run `npm run settings:doc`.");
      process.exit(1);
    }
    console.log("settings table is current");
  } else if (next !== doc) {
    writeFileSync(RUNBOOK, next);
    console.log("RUNBOOK-operations.md: settings table rewritten");
  } else {
    console.log("RUNBOOK-operations.md: settings table already current");
  }
}
